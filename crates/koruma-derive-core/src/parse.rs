/// Fully parsed and normalized `#[koruma::validator]` struct-field metadata.
#[derive(Clone, Debug)]
pub struct ValidatorStructSpec {
    pub fields: Vec<ValidatorFieldSpec>,
    pub value_index: usize,
}

impl ValidatorStructSpec {
    pub fn value_field(&self) -> &ValidatorFieldSpec {
        &self.fields[self.value_index]
    }

    pub fn value_spec(&self) -> &ValidatorValueSpec {
        let ValidatorFieldRole::Value(value) = &self.value_field().role else {
            unreachable!("value_index should point at a value field")
        };
        value
    }
}

#[derive(Clone, Debug)]
pub enum ValidatorFieldKorumaItem {
    Value(ValidatorValueSpec),
    Setter(ParsedSetterOptions),
}

#[derive(Clone, Debug, Default)]
pub struct ParsedSetterOptions {
    method: Option<Ident>,
    into: bool,
    required: bool,
    default: SetterDefault,
}

#[derive(Clone, Debug)]
struct ValidatorFieldMarker {
    ident: Ident,
    item: ValidatorFieldKorumaItem,
}

#[derive(Clone, Debug, Default)]
struct ValidatorFieldKorumaAttr {
    markers: Vec<ValidatorFieldMarker>,
}

impl Default for SetterDefault {
    fn default() -> Self {
        Self::None
    }
}

impl Parse for ValidatorFieldKorumaAttr {
    fn parse(input: ParseStream) -> Result<Self> {
        let mut attr = ValidatorFieldKorumaAttr::default();

        while !input.is_empty() {
            let ident: Ident = input.parse()?;
            let item = if ident == "value" {
                let capture = if input.peek(syn::token::Paren) {
                    parse_value_capture_policy(input)?
                } else {
                    CapturePolicy::CloneInput
                };
                ValidatorFieldKorumaItem::Value(ValidatorValueSpec { capture })
            } else if ident == "skip_capture" {
                return Err(context_error(&ident, KorumaAttrContext::ValidatorField));
            } else if ident == "setter" {
                ValidatorFieldKorumaItem::Setter(parse_setter_options(input)?)
            } else {
                return Err(context_error(&ident, KorumaAttrContext::ValidatorField));
            };
            attr.markers.push(ValidatorFieldMarker { ident, item });

            if input.peek(Token![,]) {
                input.parse::<Token![,]>()?;
            } else {
                break;
            }
        }

        Ok(attr)
    }
}

fn parse_setter_options(input: ParseStream) -> Result<ParsedSetterOptions> {
    let content;
    parenthesized!(content in input);
    let mut options = ParsedSetterOptions::default();

    while !content.is_empty() {
        let ident: Ident = content.parse()?;
        if ident == "into" {
            options.into = true;
        } else if ident == "required" {
            options.required = true;
        } else if ident == "name" {
            content.parse::<Token![=]>()?;
            options.method = Some(content.parse()?);
        } else if ident == "default" {
            options.default = if content.peek(Token![=]) {
                content.parse::<Token![=]>()?;
                SetterDefault::Expr(content.parse()?)
            } else {
                SetterDefault::Default
            };
        } else {
            return Err(Error::new(
                ident.span(),
                format!(
                    "unsupported `#[koruma(setter({ident}))]` option; supported options are `into`, `required`, `name`, and `default`"
                ),
            ));
        }

        if content.peek(Token![,]) {
            content.parse::<Token![,]>()?;
        } else {
            break;
        }
    }

    Ok(options)
}

fn parse_value_capture_policy(input: ParseStream) -> Result<CapturePolicy> {
    let content;
    parenthesized!(content in input);

    let key: Ident = content.parse()?;
    if key != "capture" {
        return Err(Error::new(
            key.span(),
            "unsupported `value(...)` option; supported option is `capture = skip`",
        ));
    }
    content.parse::<Token![=]>()?;
    let policy: Ident = content.parse()?;
    let capture = if policy == "skip" {
        CapturePolicy::Skip
    } else {
        return Err(Error::new(
            policy.span(),
            "unsupported capture policy; supported policy is `skip`",
        ));
    };

    if content.peek(Token![,]) {
        content.parse::<Token![,]>()?;
    }
    if !content.is_empty() {
        return Err(Error::new(
            content.span(),
            "unexpected extra tokens in `value(...)`; supported option is `capture = skip`",
        ));
    }

    Ok(capture)
}

fn validator_field_attr(attr: &ExpandedAttr) -> Result<ValidatorFieldKorumaAttr> {
    attr.parse_args::<ValidatorFieldKorumaAttr>()
}

/// Describes whether the `#[koruma(value)]` field should capture the input
/// value in derived validation errors.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum CapturePolicy {
    /// Store the validated value in the generated validator instance.
    CloneInput,
    /// Skip storing the validated value and leave the field at its default.
    Skip,
}

/// Parsed information about the field marked with `#[koruma(value)]`.
#[derive(Clone, Debug)]
pub struct ValueFieldInfo {
    pub name: Ident,
    pub ty: Type,
    pub capture: CapturePolicy,
}

/// Parse all fields in a `#[koruma::validator]` struct into typed metadata.
///
/// This strict API proves that exactly one field is marked `#[koruma(value)]`,
/// value fields do not also define setter metadata, all validator-field
/// `#[koruma(...)]` attributes use validator-field grammar, and required
/// setters are not also defaulted.
pub fn parse_validator_fields_strict(input: &ItemStruct) -> Result<ValidatorStructSpec> {
    parse_validator_fields(input, true)?.ok_or_else(|| {
        Error::new_spanned(
            input,
            "koruma::validator requires a field marked with #[koruma(value)].\n\
             Example:\n\
             #[koruma(value)]\n\
             actual: Option<i32>",
        )
    })
}

fn parse_validator_fields(
    input: &ItemStruct,
    require_value: bool,
) -> Result<Option<ValidatorStructSpec>> {
    let Fields::Named(ref fields) = input.fields else {
        return Ok(None);
    };

    let mut parsed_fields: Vec<ValidatorFieldSpec> = Vec::new();
    let mut value_index: Option<usize> = None;

    for field in &fields.named {
        let Some(field_name) = field.ident.clone() else {
            continue;
        };

        let mut value: Option<(Ident, ValidatorValueSpec)> = None;
        let mut setter = ValidatorSetterSpec {
            method: field_name.clone(),
            into: false,
            required: false,
            default: SetterDefault::None,
        };
        let mut has_setter_metadata = false;

        for attr in field.attrs.to_vec().find_attribute("koruma") {
            let markers = validator_field_attr(&attr)?;
            if markers.markers.is_empty() {
                return Err(Error::new_spanned(
                    attr.path(),
                    format!(
                        "`#[koruma(...)]` on validator fields must contain {}; data-field modifiers like `nested`, `newtype`, and validators are only valid on derive data fields",
                        KorumaAttrContext::ValidatorField.accepted_items()
                    ),
                ));
            }

            for marker in markers.markers {
                match marker.item {
                    ValidatorFieldKorumaItem::Value(value_spec) => {
                        if value.is_some() {
                            return Err(Error::new(
                                marker.ident.span(),
                                format!(
                                    "field `{field_name}` has multiple `#[koruma(value)]` markers"
                                ),
                            ));
                        }
                        value = Some((marker.ident, value_spec));
                    },
                    ValidatorFieldKorumaItem::Setter(setter_options) => {
                        has_setter_metadata = true;
                        merge_setter_options(&mut setter, setter_options);
                    },
                }
            }
        }

        if value.is_some() && has_setter_metadata {
            return Err(Error::new_spanned(
                field,
                "`#[koruma(value)]` fields cannot also use `#[koruma(setter(...))]`",
            ));
        }

        if setter.required && !matches!(setter.default, SetterDefault::None) {
            return Err(Error::new_spanned(
                field,
                "`required` and `default` cannot be combined in `#[koruma(setter(...))]`",
            ));
        }

        let role = if let Some((_, value_spec)) = value {
            if let Some(existing_index) = value_index {
                let existing = &parsed_fields[existing_index].name;
                return Err(Error::new(
                    field_name.span(),
                    format!(
                        "koruma::validator requires exactly one `#[koruma(value)]` field, found both `{}` and `{}`",
                        existing, field_name
                    ),
                ));
            }
            value_index = Some(parsed_fields.len());
            ValidatorFieldRole::Value(value_spec)
        } else {
            ValidatorFieldRole::Setter(setter)
        };

        parsed_fields.push(ValidatorFieldSpec {
            name: field_name,
            ty: field.ty.clone(),
            role,
        });
    }

    match value_index {
        Some(value_index) => Ok(Some(ValidatorStructSpec {
            fields: parsed_fields,
            value_index,
        })),
        None if require_value => Ok(None),
        None => Ok(None),
    }
}

fn merge_setter_options(setter: &mut ValidatorSetterSpec, options: ParsedSetterOptions) {
    if let Some(method) = options.method {
        setter.method = method;
    }
    setter.into |= options.into;
    setter.required |= options.required;
    if !matches!(options.default, SetterDefault::None) {
        setter.default = options.default;
    }
}

/// Find the field marked with `#[koruma(value)]` and return its parsed info.
///
/// This strict variant validates that validator structs use exactly one
/// `#[koruma(value)]` marker and that validator-field `#[koruma(...)]`
/// attributes only contain the `value`, `value(capture = skip)`, and `setter(...)` markers.
pub fn find_value_field_info_strict(input: &ItemStruct) -> Result<Option<ValueFieldInfo>> {
    Ok(parse_validator_fields(input, false)?.map(|spec| {
        let value_field = spec.value_field();
        let ValidatorFieldRole::Value(value) = &value_field.role else {
            unreachable!("value field should have value role")
        };
        ValueFieldInfo {
            name: value_field.name.clone(),
            ty: value_field.ty.clone(),
            capture: value.capture,
        }
    }))
}

/// Find the field marked with `#[koruma(value)]` and return its name and type.
///
/// This strict variant validates that validator structs use exactly one
/// `#[koruma(value)]` marker and that validator-field `#[koruma(...)]`
/// attributes only contain the `value`, `value(capture = skip)`, and `setter(...)` markers.
pub fn find_value_field_strict(input: &ItemStruct) -> Result<Option<(Ident, Type)>> {
    Ok(find_value_field_info_strict(input)?.map(|info| (info.name, info.ty)))
}

/// Parsed showcase attribute:
/// `#[showcase(name = "...", description = "...", create = |input| { ... }, input_type = Text)]`
///
/// The `create` closure takes a `&str` and returns the validator instance.
/// Required `input_type` must be `Text` or `Numeric`.
/// Optional `module` can be "string", "format", "numeric", "collection", or "general".
/// `module` defaults to `general` when omitted.
#[cfg(feature = "internal-showcase")]
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum ShowcaseInputType {
    /// Showcases that expect text input.
    Text,
    /// Showcases that expect numeric input.
    Numeric,
}

/// Parsed and validated `module` selector for showcase validators.
#[cfg(feature = "internal-showcase")]
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum ShowcaseModule {
    String,
    Format,
    Numeric,
    Collection,
    General,
}

#[cfg(feature = "internal-showcase")]
#[derive(Clone, Debug)]
pub struct ShowcaseAttr {
    pub name: syn::LitStr,
    pub description: syn::LitStr,
    pub create: syn::ExprClosure,
    pub input_type: ShowcaseInputType,
    pub module: Option<ShowcaseModule>,
}

#[cfg(feature = "internal-showcase")]
impl Parse for ShowcaseAttr {
    fn parse(input: ParseStream) -> Result<Self> {
        let mut name: Option<syn::LitStr> = None;
        let mut description: Option<syn::LitStr> = None;
        let mut create: Option<syn::ExprClosure> = None;
        let mut input_type: Option<Ident> = None;
        let mut module: Option<ShowcaseModule> = None;

        while !input.is_empty() {
            let ident: Ident = input.parse()?;
            input.parse::<Token![=]>()?;

            match ident.to_string().as_str() {
                "name" => {
                    name = Some(input.parse()?);
                },
                "description" => {
                    description = Some(input.parse()?);
                },
                "create" => {
                    create = Some(input.parse()?);
                },
                "input_type" => {
                    input_type = Some(input.parse()?);
                },
                "module" => {
                    let parsed_module: syn::LitStr = input.parse()?;
                    module = Some(parse_showcase_module(parsed_module)?);
                },
                other => {
                    return Err(Error::new(
                        ident.span(),
                        format!("unknown showcase attribute: {}", other),
                    ));
                },
            }

            if input.peek(Token![,]) {
                input.parse::<Token![,]>()?;
            }
        }

        Ok(ShowcaseAttr {
            name: name
                .ok_or_else(|| Error::new(input.span(), "showcase requires `name` attribute"))?,
            description: description.ok_or_else(|| {
                Error::new(input.span(), "showcase requires `description` attribute")
            })?,
            create: create
                .ok_or_else(|| Error::new(input.span(), "showcase requires `create` attribute"))?,
            input_type: match input_type {
                Some(input_type) => parse_showcase_input_type(input_type)?,
                None => {
                    return Err(Error::new(
                        input.span(),
                        "showcase requires `input_type` attribute",
                    ));
                },
            },
            module,
        })
    }
}

#[cfg(feature = "internal-showcase")]
fn parse_showcase_input_type(input_type: Ident) -> Result<ShowcaseInputType> {
    match input_type.to_string().as_str() {
        "Text" => Ok(ShowcaseInputType::Text),
        "Numeric" => Ok(ShowcaseInputType::Numeric),
        _ => Err(Error::new(
            input_type.span(),
            "showcase `input_type` must be `Text` or `Numeric`",
        )),
    }
}

#[cfg(feature = "internal-showcase")]
fn parse_showcase_module(module: syn::LitStr) -> Result<ShowcaseModule> {
    match module.value().as_str() {
        "string" => Ok(ShowcaseModule::String),
        "format" => Ok(ShowcaseModule::Format),
        "numeric" => Ok(ShowcaseModule::Numeric),
        "collection" => Ok(ShowcaseModule::Collection),
        "general" => Ok(ShowcaseModule::General),
        _ => Err(Error::new(
            module.span(),
            "showcase `module` must be one of: \"string\", \"format\", \"numeric\", \"collection\", or \"general\"",
        )),
    }
}

/// Find and parse showcase attribute from struct
#[cfg(feature = "internal-showcase")]
pub fn find_showcase_attr(input: &ItemStruct) -> Result<Option<ShowcaseAttr>> {
    for attr in &input.attrs {
        if attr.path().is_ident("showcase") {
            return Ok(Some(attr.parse_args::<ShowcaseAttr>()?));
        }
    }
    Ok(None)
}
